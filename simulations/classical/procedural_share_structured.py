#!/usr/bin/env python3
"""Tier 2 toy model (proof-of-concept): blind vs informed inputs on STRUCTURED
candidate pools (shared eigenbasis; Clifford subsets), where a zero expected
input-side gap is no longer forced by Haar invariance.

    *** TOY MODEL. Proof-of-concept for the shape of a curve in a two-qubit
    *** toy. It is NOT evidence about hadronic or QCD physics and makes no
    *** physical claim of any kind.

Pure numpy. Imports procedural_share_informed.py (variants, Holevo, stats) and
procedural_share_surface.py (GAD, nested readout, shares). Run:

    python simulations/classical/procedural_share_structured.py            # all pools, T=1 (+T=0, inf)
    python simulations/classical/procedural_share_structured.py --pool eigbasis,clifford2 --seeds 20
    python simulations/classical/procedural_share_structured.py --markdown --no-robust-T

POOLS (each drawn and SHA-256 hashed, with the control unitaries V_f, before
any noise parameter exists; hash re-checked after every condition). Pool
draw s uses default_rng([s, tag]); canonical draw s = 2026; ensemble s = 1..K.
  eigbasis           U_f = W diag(e^{i phi_f}) W^dag, phi_f iid uniform on
                     [0, 2pi)^4, ONE Haar W per draw shared by all 50 f.
  eigbasis-pert      U_f = exp(i eps H_f) W diag(e^{i phi_f}) W^dag, H_f GUE
                     with spectral norm 1, eps = --eps (default 0.1).
  eigbasis-hadamard  as eigbasis with fixed W = H (x) H (randomness: phases).
  eigbasis-identity  W = I: diagonal in the readout basis. CONSTRUCTION-FORCED
                     cases, see TRAPS.
  clifford1          random 50-subset (per draw) of C1 x C1 (576 elements mod
                     phase; C1 = 24-element single-qubit Clifford group).
  clifford1-full     the 24 elements C1 (x) I. DETERMINISTIC: no pool
                     randomness (only V_f for 'rand' varies with the seed).
  clifford2          random 50-subset (per draw) of the two-qubit Clifford
                     group (11520 elements mod phase, generated by BFS from
                     H, S on each qubit and CNOT).
  H(F) = log2 |pool| (50, or 24 for clifford1-full).

VARIANTS: as procedural_share_informed.py (blind |m0>, blindalt |m1>,
  (a) eigen, (b) phase, (c) fixedpt, rand V_f|m0>, readable U_f^dag|m b_f>,
  gphase), with ONE change: eigenvectors come from a joint diagonalization
  of the commuting Hermitian parts of U_f (eigh of (U+U^dag)/2 +
  gamma_E (U-U^dag)/(2i)), which is orthonormal even when U_f is degenerate
  (Clifford). Eigenphases are rounded to 1e-9, -pi is mapped to +pi, and the
  sort is stable; inside a degenerate eigenspace the basis is whatever eigh
  returns (deterministic in U_f, not canonical). Same phase convention.

TRAPS (stated, not hidden)
  * Only the MESSAGE-AVERAGED input matters for I(F;Y): with M unknown and
    independent across uses, P(y1,y2|f) = P1(y1|f) P1(y2|f) where P1 is the
    law of N(U_f sigma_f U_f^dag), sigma_f = (1/2) sum_m |psi_fm><psi_fm|.
    For eigen, fixedpt and readable, U_f sigma_f U_f^dag does not depend on
    U_f's action (eigen/fixedpt: sigma_f is a mixture of two eigenprojectors
    of U_f, the cross terms of fixedpt cancel; readable: it is the averaged
    state of |m b_f>). So in EVERY pool, including CE-10's Haar pool, the
    informed I(F;Y) of (a), (c) and readable is carried entirely by the
    input: F -> sigma_f -> Y is Markov and I(F;Y) <= chi_in. Only (b) phase
    and rand let U_f act on the hint.
  * Shared eigenbasis, eigen (a): the eigenvector SET is the same for every
    f, but (a) picks the two eigenvectors with the smallest eigenphases, so
    WHICH columns of W are used depends on f. (a) is therefore f-dependent,
    but sigma_f carries only the unordered pair {k0, k1}: 6 values, so at
    most 6 distinct output laws and I(F;Y) <= log2 6. Guaranteed.
  * W = H (x) H: every eigenprojector is a Hadamard-basis state with all Z
    populations 1/4, and GAD's Z statistics see only populations; sigma_f
    for (a) and (c) mixes two such projectors, so their informed
    I(F;Y) = 0 and gap = -I(F;Y)_blind, by construction.
  * Pools acting on qubit A only (clifford1-full): the blind averaged input
    (I/2) (x) |0><0| is invariant, so blind (and blindalt) I(F;Y) = 0 by
    construction and every gap equals the informed I(F;Y) >= 0. For C1 x C1
    the blind condition sees only qubit B's Clifford acting on |0> (at most
    6 stabilizer states -> at most 6 blind output laws).
  * W = I with Z readout: GAD maps diagonals to diagonals, so Z readout sees
    only input populations. U_f diagonal does not change populations. Hence
      blind, blindalt: I(F;Y) = 0 exactly (f invisible);
      phase: all populations 1/4 -> I(F;Y) = 0; gap = 0 by construction;
      gphase: 0;
      eigen, fixedpt: populations reveal the f-dependent SELECTION (which
        basis states), not U_f's action -> gap >= 0, by construction;
      rand: populations of V_f|m0> reveal the random label -> leak by
        construction;
      readable: 1-bit tag -> by construction.
  * rand on ANY pool: U_f V_f with V_f Haar is Haar for every U_f, so the
    rand informed surface is distributed as a Haar-pool blind surface; its
    gap compares a structured blind to a Haar-like informed condition.
  * Clifford pools: stabilizer inputs map to stabilizer states, whose Z
    statistics are uniform on affine subsets, so many f share one output law.
    The number of distinct output laws is reported (it bounds
    I(F;Y) <= log2 #laws).
  * Every pool: gap = 0 at g = 1; gphase gap = 0 exactly; readable
    I(F;Y) <= 1 bit; I(F;Y) <= min(log2 r, H(F)) and <= chi_out (Holevo).
STATISTICS: as CE-10. Randomness = independent pool draws (W, phases,
  perturbations, Clifford subsets, V_f), blind and informed paired on each
  draw. H0: E_draw[gap] = 0. Aggregate per-draw grid-mean gap (g < 1):
  two-sided sign-flip (20000), bootstrap 95% CI, Holm across tested variants
  within a pool; per-point sign-flip with Holm across the 40 points (gaps
  below 1e-12 in magnitude are set to exactly 0 first, so floating-point
  residue of an exact zero cannot register as significant). A
  variant whose per-draw gap does not vary (deterministic pool) is reported
  as an exact value, untested. 'Resolution floor' of a pool = largest 95% CI
  half-width among its tested non-deterministic variants.
BALANCE SHEET: X = M (theorem), X = (M, hint) (not a theorem), I(X,F;Y) <= H(Y).
"""

