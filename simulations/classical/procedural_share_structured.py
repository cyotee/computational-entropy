def _gue(rng):
    A = rng.standard_normal((4, 4)) + 1j * rng.standard_normal((4, 4))
    Hm = (A + A.conj().T) / 2
    return Hm / np.max(np.abs(np.linalg.eigvalsh(Hm)))


def _expi(Hm, eps):
    w, v = np.linalg.eigh(Hm)
    return (v * np.exp(1j * eps * w)) @ v.conj().T


def build_pool(kind: str, seed: int, n: int = 50, eps: float = 0.1):
    """Pool (N,4,4) and control unitaries V (N,4,4). Depends only on (kind, seed, n, eps)."""
    rng = np.random.default_rng([seed, POOL_TAG[kind]])
    if kind.startswith("eigbasis"):
        if kind in ("eigbasis", "eigbasis-pert"):
            W = pss.haar_unitary(4, rng)
        elif kind == "eigbasis-hadamard":
            W = np.kron(_H, _H)
        else:
            W = np.eye(4, dtype=complex)
        phi = rng.uniform(0, 2 * math.pi, size=(n, 4))
        pool = np.stack([(W * np.exp(1j * ph)) @ W.conj().T for ph in phi])
        if kind == "eigbasis-pert":
            pool = np.stack([_expi(_gue(rng), eps) @ U for U in pool])
    elif kind == "clifford1":
        c1 = clifford1()
        idx = rng.choice(len(c1) ** 2, size=n, replace=False)
        pool = np.stack([np.kron(c1[i // len(c1)], c1[i % len(c1)]) for i in idx])
    elif kind == "clifford1-full":
        pool = np.stack([np.kron(c, _I2) for c in clifford1()])
    elif kind == "clifford2":
        c2 = clifford2()
        idx = rng.choice(len(c2), size=n, replace=False)
        pool = c2[np.sort(idx)].copy()
    else:
        raise ValueError(kind)
    pool = np.ascontiguousarray(pool)
    pool.setflags(write=False)
    rv = np.random.default_rng([seed, 5000])
    V = np.stack([pss.haar_unitary(4, rv) for _ in range(len(pool))])
    V.setflags(write=False)
    return pool, V, pin.all_hash(pool, V)


