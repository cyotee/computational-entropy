def self_checks():
    assert len(clifford1()) == 24, len(clifford1())
    assert len(clifford2()) == 11520, len(clifford2())
    for U in clifford2()[::997]:
        assert np.allclose(U.conj().T @ U, np.eye(4), atol=1e-12)
    # degeneracy-safe eig reproduces CE-10's eig on a generic unitary
    U = pss.haar_unitary(4, np.random.default_rng(1))
    w1, v1 = eig_sorted(U)
    w2, v2 = pin.eig_sorted(U)
    assert np.allclose(w1, w2) and np.allclose(np.abs(v1.conj().T @ v2), np.eye(4), atol=1e-8)
    # W = I trap: blind I(F;Y) = 0 exactly, phase I(F;Y) = 0 exactly
    pool, V, _ = build_pool("eigbasis-identity", 3)
    for var in ("blind", "phase"):
        psi, S = inputs(var, pool, V)
        R = surface(pool, psi, S, np.array([0.0, 0.4]), [16], 0.73)
        assert np.abs(R["IFY"]).max() < 1e-9, var
    # shared eigenbasis: eigen output laws <= 12
    pool, V, _ = build_pool("eigbasis", 3)
    psi, S = inputs("eigen", pool, V)
    assert surface(pool, psi, S, np.array([0.0]), [16], 0.73)["laws"].max() <= 6
    # eigen / fixedpt / readable: message-averaged state after U_f carries no U_f action
    for var in ("eigen", "fixedpt", "readable"):
        psi, S = inputs(var, pool, V)
        sig = np.einsum("fma,fmb->fab", psi, psi.conj()) / 2
        after = np.einsum("fab,fbc,fdc->fad", pool, sig, pool.conj())
        if var == "readable":
            assert np.allclose(after[0], after[2]) and np.allclose(after[1], after[3])
        else:
            assert np.allclose(after, sig, atol=1e-9)
    # local pool on qubit A leaves the blind averaged input I/2 (x) |0><0| invariant
    pool, V, _ = build_pool("clifford1-full", 1)
    psi, S = inputs("blind", pool, V)
    assert np.abs(surface(pool, psi, S, np.array([0.0, 0.5]), [16], 0.73)["IFY"]).max() < 1e-9


