# Inputs (CE-10 variants; degeneracy-safe eigendecomposition)
# ---------------------------------------------------------------------------

def eig_sorted(U):
    M = (U + U.conj().T) / 2 + EULER_GAMMA * (U - U.conj().T) / 2j
    _, v = np.linalg.eigh(M)
    lam = np.einsum("ak,ab,bk->k", v.conj(), U, v)
    assert np.allclose(U @ v, v * lam, atol=1e-8), "joint diagonalization failed"
    ang = np.round(np.angle(lam), 9)
    ang[ang <= -math.pi + 1e-9] = math.pi
    order = np.argsort(ang, kind="stable")
    lam, v = lam[order], v[:, order].copy()
    for k in range(4):
        i = int(np.argmax(np.round(np.abs(v[:, k]), 9)))
        v[:, k] *= np.conj(v[i, k]) / abs(v[i, k])
    assert np.allclose(v.conj().T @ v, np.eye(4), atol=1e-8)
    return lam, v


def inputs(variant, pool, V):
    nf = pool.shape[0]
    e = np.eye(4, dtype=complex)
    psi = np.zeros((nf, 2, 4), dtype=complex)
    S = np.zeros(nf, dtype=int)
    for f in range(nf):
        U = pool[f]
        if variant == "blind":
            psi[f] = [e[0], e[2]]
        elif variant == "blindalt":
            psi[f] = [e[1], e[3]]
        elif variant == "gphase":
            psi[f] = np.exp(2j * math.pi * f / nf) * np.array([e[0], e[2]])
            S[f] = f
        elif variant == "rand":
            psi[f] = [V[f][:, 0], V[f][:, 2]]
            S[f] = f
        elif variant == "readable":
            b = f % 2
            psi[f] = [U.conj().T @ e[0 + b], U.conj().T @ e[2 + b]]
            S[f] = b
        else:
            w, v = eig_sorted(U)
            S[f] = f
            if variant == "eigen":
                psi[f] = [v[:, 0], v[:, 1]]
            elif variant == "phase":
                ph = np.exp(1j * np.angle(w)) / 2
                psi[f] = [ph, ph * np.array([1, 1, -1, -1])]
            elif variant == "fixedpt":
                d = np.round(np.abs(w - 1), 9)
                n_, q = int(np.argmin(d)), int(np.argmax(d))
                if n_ == q:  # U_f proportional to identity: no near/far split
                    q = (n_ + 1) % 4
                psi[f] = [(v[:, n_] + v[:, q]) / math.sqrt(2), (v[:, n_] - v[:, q]) / math.sqrt(2)]
            else:
                raise ValueError(variant)
    G = np.einsum("fma,fna->fmn", psi.conj(), psi)
    assert np.allclose(G, np.eye(2)[None], atol=1e-8), f"{variant}: inputs not orthonormal"
    return psi, S


def n_laws(cond):
    """Number of distinct message-marginal output laws P(y|f) (bounds I(F;Y) <= log2 #laws)."""
    rows = np.round(cond.mean(axis=1), 9) + 0.0
    return len({r.tobytes() for r in rows})


def surface(pool, psi, S, gammas, ranks, p, extra=False):
    keys = ("HFgY", "IFY", "IXY", "Hy", "IMS", "IMF", "chi_out", "laws")
    R = {k: np.zeros((len(gammas), len(ranks))) for k in keys}
    for i, g in enumerate(gammas):
        rho = pin.out_states(pool, psi, float(g), p)
        if extra:
            R["chi_out"][i, :] = pin.holevo_block(rho.mean(axis=1))
        for j, r in enumerate(ranks):
            c = pss.joint_law_nested(rho, r)
            s = pss.shares(c)
            R["HFgY"][i, j], R["IFY"][i, j], R["IXY"][i, j], R["Hy"][i, j] = s["HFgY"], s["IFY"], s["IXY"], s["Hy"]
            R["laws"][i, j] = n_laws(c)
            if extra:
                R["IMS"][i, j], R["IMF"][i, j] = pin.I_label_Y(c, S)
    return R


